def _now_iso() -> str:
    return _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")


def _repo_root_from(brief_path: Path) -> Path:
    """
    Walk up from the brief path until we find the repo root marker.
    We use the presence of `docs/handoff/00_LATEST_CODEX_HANDOFF.md` as the marker
    (every repo state we care about contains it). Falls back to brief_path.parents[3]
    which matches docs/automation/render_briefs/*.json layout.
    """
    p = brief_path.resolve()
    for parent in [p] + list(p.parents):
        candidate = parent / "docs" / "handoff" / "00_LATEST_CODEX_HANDOFF.md"
        if candidate.exists():
            return parent
    # Fallback: assume layout docs/automation/render_briefs/<brief>.json
    try:
        return p.parents[3]
    except IndexError:
        return p.parent


def _sha256_of_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _aspect_ratio_to_size(aspect_ratio: str, resolution_target_px: Optional[str]) -> Tuple[int, int]:
    """
    Convert brief aspect_ratio + optional resolution_target_px into (width, height).
    Deterministic fallbacks if resolution_target_px is malformed or None.
    """
    if resolution_target_px and "x" in resolution_target_px:
        try:
            w_str, h_str = resolution_target_px.lower().split("x", 1)
            w = int("".join(ch for ch in w_str if ch.isdigit()))
            h = int("".join(ch for ch in h_str if ch.isdigit()))
            if w > 0 and h > 0:
                return w, h
        except (ValueError, AttributeError):
            pass
    # Fallback by aspect_ratio
    table = {
        "2.35:1": (2352, 1000),
        "16:9": (1920, 1080),
        "9:16": (1080, 1920),
        "1:1": (1024, 1024),
        "4:5": (1024, 1280),
        "3:4": (960, 1280),
        "4:3": (1280, 960),
        "2.76:1": (2208, 800),
    }
    return table.get(aspect_ratio, (1024, 1024))


