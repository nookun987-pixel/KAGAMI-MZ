def allocate_run_folder(repo_root: Path, output_root_rel: str, brief_id: str) -> Tuple[Path, int]:
    """
    Build docs/automation/render_briefs/runs/<BRIEF_ID>/attempt_<NNN>/.
    NNN auto-increments to the first unused 3-digit number starting at 001.
    """
    base = repo_root / output_root_rel / (brief_id or "UNKNOWN_BRIEF_ID")
    base.mkdir(parents=True, exist_ok=True)
    n = 1
    while True:
        folder = base / f"attempt_{n:03d}"
        if not folder.exists():
            folder.mkdir(parents=True, exist_ok=False)
            return folder, n
        n += 1
        if n > 999:
            # Defensive: should never happen in practice
            raise RuntimeError("Exhausted attempt_NNN counter (>999) for brief_id=%s" % brief_id)


