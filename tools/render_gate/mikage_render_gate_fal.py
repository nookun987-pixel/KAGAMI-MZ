def main(argv: Optional[list] = None) -> int:
    parser = argparse.ArgumentParser(
        prog=f"{TOOL_NAME}.py",
        description="Mikage render gate (FAL) V0.1 — hard-gated CLI for image render attempts.",
    )
    parser.add_argument(
        "--brief",
        required=True,
        help="Repo-relative or absolute path to a prompt_pack/v0.1 JSON brief sidecar.",
    )
    parser.add_argument(
        "--config",
        default=None,
        help="Path to render gate config JSON. Defaults to "
        "tools/render_gate/mikage_render_gate_config.json next to this script.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Never call FAL. Write reports and exit cleanly. Overrides all unlock gates.",
    )
    args = parser.parse_args(argv)

    notes: list = []

    # ------------------------------------------------------------------
    # Resolve paths
    # ------------------------------------------------------------------
    brief_path = Path(args.brief).resolve()
    if not brief_path.exists():
        sys.stderr.write(f"ERROR: brief not found: {brief_path}\n")
        return 2

    repo_root = _repo_root_from(brief_path)

    if args.config:
        config_path = Path(args.config).resolve()
    else:
        config_path = (repo_root / "tools" / "render_gate" / "mikage_render_gate_config.json").resolve()
    if not config_path.exists():
        sys.stderr.write(f"ERROR: config not found: {config_path}\n")
        return 2

    # ------------------------------------------------------------------
    # Load config + brief
    # ------------------------------------------------------------------
    try:
        cfg = load_config(config_path)
    except Exception as e:
        sys.stderr.write(f"ERROR: failed to parse config: {e}\n")
        return 2

    try:
        brief = load_brief(brief_path)
    except Exception as e:
        sys.stderr.write(f"ERROR: failed to parse brief JSON: {e}\n")
        return 2

    sha_before = _sha256_of_file(brief_path)

    fields = extract_brief_fields(brief)
    brief_id = fields["brief_id"] or "UNKNOWN_BRIEF_ID"
    schema_version = fields["schema_version"]
    if schema_version and schema_version != SCHEMA_EXPECTED:
        notes.append(
            f"schema_version='{schema_version}' does not match expected '{SCHEMA_EXPECTED}'. "
            "Tool proceeds but operator should reconcile."
        )

    # ------------------------------------------------------------------
    # Decide gate outcome
    # ------------------------------------------------------------------
    operator_token = fields["operator_approval_token"]
    operator_token_present = bool(operator_token)
    model_id = cfg.get("model_id", "CHUA_XAC_NHAN")
    fal_key = os.environ.get("FAL_KEY") or os.environ.get("FAL_API_KEY")
    fal_key_present = bool(fal_key)

    # Determine status. Order of precedence matters:
    # dry-run is a CLI override (operator-explicit "don't call").
    # Otherwise the safety gates trigger from strongest invariant first.
    if args.dry_run:
        status = STATUS_DRY_RUN
    elif not operator_token_present:
        status = STATUS_BLOCKED_APPROVAL
    elif model_id == "CHUA_XAC_NHAN":
        status = STATUS_MODEL_CHUA_XAC_NHAN
    elif not fal_key_present:
        status = STATUS_FAL_KEY_MISSING
    else:
        status = None  # will be set after API call

    # ------------------------------------------------------------------
    # Allocate run folder + write deterministic artifacts
    # ------------------------------------------------------------------
    try:
        run_folder, attempt_n = allocate_run_folder(
            repo_root=repo_root,
            output_root_rel=cfg.get("output_root", "docs/automation/render_briefs/runs"),
            brief_id=brief_id,
        )
    except Exception as e:
        sys.stderr.write(f"ERROR: failed to allocate run folder: {e}\n")
        return 2

    # Compact prompt + negative — routed by brief_id via select_compact_prompt().
    # V0.1 path preserved for legacy briefs; V0.2 brief_id routes to redesigned
    # front-loaded-positive compact prompt. Unknown brief_ids fall back to V0.1
    # and a note is recorded.
    compact_prompt, compact_negative, prompt_mode_label = select_compact_prompt(brief_id)
    known_brief_ids = {
        "BRIEF_COMMANDER_LYRE_PHASE_1_IMPERIAL_DUTY_V0_1",
        "BRIEF_COMMANDER_LYRE_PHASE_1_IMPERIAL_DUTY_V0_2",
    }
    if brief_id not in known_brief_ids:
        notes.append(
            f"brief_id '{brief_id}' is not a known compact-prompt routing target. "
            f"Falling back to V0.1 Lyre Phase 1 compact prompt. Add a new branch in "
            f"select_compact_prompt() for this brief in a future tool revision."
        )

    width, height = _aspect_ratio_to_size(
        aspect_ratio=fields["aspect_ratio"] or "2.35:1",
        resolution_target_px=fields["resolution_target_px"],
    )

    fal_request = build_fal_request(
        compact_prompt=compact_prompt,
        compact_negative=compact_negative,
        width=width,
        height=height,
        aspect_ratio=fields["aspect_ratio"] or "2.35:1",
        model_id=model_id,
        prompt_mode=prompt_mode_label,
    )

    write_text(run_folder / "prompt_compact.txt", compact_prompt + "\n")
    write_text(run_folder / "negative_compact.txt", compact_negative + "\n")
    write_json(run_folder / "fal_request.json", fal_request)

    # ------------------------------------------------------------------
    # Maybe call FAL
    # ------------------------------------------------------------------
    api_called = False
    fal_response: Optional[Dict[str, Any]] = None
    fal_request_id: Optional[str] = None
    actual_output_path: Optional[str] = None
    cost_estimate = "CHUA_XAC_NHAN"

    if status is None:
        # All gates open; perform the API call.
        endpoint_url = cfg.get("fal_endpoint_template", "https://fal.run/{model_id}").format(
            model_id=model_id
        )
        ok, resp, err = call_fal(
            endpoint_url=endpoint_url,
            api_key=fal_key or "",
            payload=fal_request,
            timeout_seconds=int(cfg.get("fal_timeout_seconds", 120)),
            user_agent=cfg.get("fal_request_user_agent", f"{TOOL_NAME}/{TOOL_VERSION}"),
        )
        api_called = True
        fal_response = resp or {}
        if not ok:
            status = STATUS_API_REQUEST_FAILED
            notes.append(f"FAL API call failed: {err}")
            write_json(run_folder / "fal_response.json", fal_response)
        else:
            write_json(run_folder / "fal_response.json", fal_response)
            fal_request_id = fal_response.get("request_id") or fal_response.get("id")
            if isinstance(fal_response.get("cost"), (int, float)):
                cost_estimate = str(fal_response.get("cost"))
            image_url = extract_image_url(fal_response)
            if image_url:
                out_path = run_folder / "output.png"
                ok_dl, err_dl = download_image(
                    image_url, out_path,
                    timeout_seconds=int(cfg.get("fal_timeout_seconds", 120)),
                    user_agent=cfg.get("fal_request_user_agent", f"{TOOL_NAME}/{TOOL_VERSION}"),
                )
                if ok_dl:
                    actual_output_path = str(out_path.relative_to(repo_root))
                    status = STATUS_RENDER_OK
                    notes.append(
                        "Output saved to run folder. NOT copied to brief output_target.output_path; "
                        "operator promotes the image only after verification report."
                    )
                else:
                    status = STATUS_API_REQUEST_FAILED
                    notes.append(f"Image download failed: {err_dl}")
            else:
                status = STATUS_API_REQUEST_FAILED
                notes.append(
                    "FAL response did not contain an image URL in any recognized shape. "
                    "See fal_response.json."
                )
    else:
        # Gated path: do not call API, do not write fal_response.json.
        if status == STATUS_BLOCKED_APPROVAL:
            notes.append(
                "operator_approval_token is null in the brief. "
                "Tool refused to call FAL. No API request was sent."
            )
        elif status == STATUS_MODEL_CHUA_XAC_NHAN:
            notes.append(
                "config.model_id is 'CHUA_XAC_NHAN' (V0.1 default safety stop). "
                "Tool refused to call FAL. No API request was sent."
            )
        elif status == STATUS_FAL_KEY_MISSING:
            notes.append(
                "Neither FAL_KEY nor FAL_API_KEY env var is set. "
                "Tool refused to call FAL. No API request was sent."
            )
        elif status == STATUS_DRY_RUN:
            notes.append(
                "--dry-run set. Tool wrote compact prompt + negative + fal_request.json "
                "and exited without contacting FAL."
            )

    # ------------------------------------------------------------------
    # Confirm source brief unchanged
    # ------------------------------------------------------------------
    sha_after = _sha256_of_file(brief_path)
    source_brief_unchanged = sha_after == sha_before
    if not source_brief_unchanged:
        notes.append(
            "WARNING: source brief sha256 changed during run. This tool MUST NOT modify "
            "the brief; investigate immediately."
        )

    # ------------------------------------------------------------------
    # Compose report
    # ------------------------------------------------------------------
    report = {
        "brief_id": brief_id,
        "source_brief_path": str(brief_path.relative_to(repo_root)) if brief_path.is_relative_to(repo_root) else str(brief_path),
        "source_brief_sha256_before": sha_before,
        "source_brief_sha256_after": sha_after,
        "source_brief_unchanged": source_brief_unchanged,
        "status": status,
        "provider": cfg.get("provider", "fal"),
        "model_id": model_id,
        "operator_approval_token_present": operator_token_present,
        "fal_api_key_env_present": fal_key_present,
        "dry_run": bool(args.dry_run),
        "api_called": api_called,
        "prompt_mode": prompt_mode_label,
        "aspect_ratio": fields["aspect_ratio"],
        "resolution_target_px": fields["resolution_target_px"],
        "resolved_width": width,
        "resolved_height": height,
        "output_path_requested_by_brief": fields["output_path_requested_by_brief"],
        "actual_output_path": actual_output_path,
        "fal_request_id": fal_request_id,
        "cost_estimate": cost_estimate,
        "verify_status": "NOT_STARTED",
        "anchor_established": "NO",
        "canon_lock": "NO",
        "asset_lock": "NO",
        "attempt_number": attempt_n,
        "run_folder": str(run_folder.relative_to(repo_root)) if run_folder.is_relative_to(repo_root) else str(run_folder),
        "tool": f"{TOOL_NAME}/{TOOL_VERSION}",
        "generated_on": _now_iso(),
        "next_safe_task": next_safe_task_for(status, brief_id),
        "notes": notes,
    }

    write_json(run_folder / "render_attempt_report.json", report)
    write_text(run_folder / "render_attempt_report.md", render_attempt_report_md(report))

    # ------------------------------------------------------------------
    # Print machine-readable summary to stdout
    # ------------------------------------------------------------------
    print(json.dumps({
        "STATUS": status,
        "BRIEF_ID": brief_id,
        "ATTEMPT": attempt_n,
        "API_CALLED": api_called,
        "DRY_RUN": bool(args.dry_run),
        "RUN_FOLDER": report["run_folder"],
        "SOURCE_BRIEF_UNCHANGED": source_brief_unchanged,
        "NEXT_SAFE_TASK": report["next_safe_task"],
    }, indent=2))

    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SystemExit:
        raise
    except Exception:
        sys.stderr.write("UNHANDLED ERROR — see traceback below.\n")
        traceback.print_exc()
        sys.exit(2)
