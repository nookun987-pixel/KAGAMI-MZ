def next_safe_task_for(status: str, brief_id: Optional[str]) -> str:
    bid = brief_id or "(brief_id missing)"
    if status == STATUS_BLOCKED_APPROVAL:
        return (
            f"OPERATOR_SET_APPROVAL_TOKEN_IN_BRIEF {bid} — issue "
            "OPERATOR_APPROVED=YES + APPROVAL_TOKEN in the brief JSON before retry."
        )
    if status == STATUS_MODEL_CHUA_XAC_NHAN:
        return (
            "OPERATOR_PICK_FAL_MODEL_ID — edit "
            "tools/render_gate/mikage_render_gate_config.json model_id to a concrete FAL model."
        )
    if status == STATUS_FAL_KEY_MISSING:
        return "OPERATOR_EXPORT_FAL_KEY_OR_FAL_API_KEY — set the env var before retry."
    if status == STATUS_DRY_RUN:
        return (
            f"OPERATOR_REVIEW_DRY_RUN_OUTPUTS for {bid}; if compact prompt + negative + "
            "fal_request.json look correct, re-run without --dry-run after also satisfying "
            "approval / model_id / FAL_KEY gates."
        )
    if status == STATUS_API_REQUEST_FAILED:
        return (
            "OPERATOR_INSPECT_FAL_RESPONSE — see fal_response.json in the attempt folder; "
            "retry only after diagnosing (auth / model / payload shape)."
        )
    if status == STATUS_RENDER_OK:
        return (
            f"COWORK_DRAFT_VERIFICATION_REPORT against brief verification_checklist for {bid}. "
            "Do NOT mark PASS, do NOT establish anchor, do NOT asset-lock — operator decides "
            "after Cowork drafts findings."
        )
    return "OPERATOR_REVIEW — unknown status."


