def call_fal(
    endpoint_url: str,
    api_key: str,
    payload: Dict[str, Any],
    timeout_seconds: int,
    user_agent: str,
) -> Tuple[bool, Optional[Dict[str, Any]], Optional[str]]:
    """
    Call FAL via stdlib urllib. Returns (ok, response_json_or_none, error_message_or_none).
    """
    body = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        endpoint_url,
        data=body,
        method="POST",
        headers={
            "Authorization": f"Key {api_key}",
            "Content-Type": "application/json",
            "Accept": "application/json",
            "User-Agent": user_agent,
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout_seconds) as resp:
            raw = resp.read().decode("utf-8", errors="replace")
            try:
                return True, json.loads(raw), None
            except json.JSONDecodeError as e:
                return False, {"raw": raw}, f"FAL returned non-JSON body: {e}"
    except urllib.error.HTTPError as e:
        raw = e.read().decode("utf-8", errors="replace") if hasattr(e, "read") else ""
        return False, {"http_status": e.code, "raw": raw}, f"HTTP {e.code} {e.reason}"
    except urllib.error.URLError as e:
        return False, None, f"URLError: {e.reason}"
    except Exception as e:  # pragma: no cover  (defensive)
        return False, None, f"Unhandled error: {type(e).__name__}: {e}"


def extract_image_url(response: Dict[str, Any]) -> Optional[str]:
    """
    Best-effort extraction of an image URL from a FAL response.
    Supports the common shapes:
       {"images": [{"url": "..."}]}, {"image": {"url": "..."}}, {"output": "..."}
    Returns None if no URL found.
    """
    if not isinstance(response, dict):
        return None
    imgs = response.get("images")
    if isinstance(imgs, list) and imgs:
        first = imgs[0]
        if isinstance(first, dict) and isinstance(first.get("url"), str):
            return first["url"]
        if isinstance(first, str):
            return first
    img = response.get("image")
    if isinstance(img, dict) and isinstance(img.get("url"), str):
        return img["url"]
    if isinstance(response.get("output"), str):
        return response["output"]
    return None


def download_image(url: str, dest: Path, timeout_seconds: int, user_agent: str) -> Tuple[bool, Optional[str]]:
    try:
        req = urllib.request.Request(url, headers={"User-Agent": user_agent})
        with urllib.request.urlopen(req, timeout=timeout_seconds) as resp:
            data = resp.read()
        dest.write_bytes(data)
        return True, None
    except Exception as e:
        return False, f"download failed: {type(e).__name__}: {e}"


